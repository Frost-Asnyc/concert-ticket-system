# Event Ticket System CLI Instructions
#
# This file is only documentation. It is written as Python comments so it
# cannot affect the running project.
#
# How to run the CLI:
#   1. Open a terminal in the project folder.
#   2. Run: python main.py
#   3. Choose a number from the menu.
#
# Main menu options:
#   1. Register
#   2. Login
#   3. View Events
#   4. Search Events
#   5. Book Ticket
#   6. My Tickets
#   7. Cancel Ticket
#   8. Exit
#   9. Add Event
#
# Extra beginner note:
#   - This project uses models/event.py for events.
#   - This project uses models/ticket.py for tickets.
#   - This project uses models/booking.py for bookings.
#   - Data is stored in data/event.json, data/ticket.json and data/booking.json.
#
# You can add events with option 9 in the simple CLI. You can also edit
# data/event.json directly while learning.

